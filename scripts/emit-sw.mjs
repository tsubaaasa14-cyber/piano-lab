import { readdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';

// Keep in sync with vite.config.ts base and public/manifest.webmanifest.
const BASE = '/piano-lab/';
const dist = path.resolve('dist');

async function walk(dir) {
  const files = [];
  for (const entry of await readdir(dir)) {
    const full = path.join(dir, entry);
    const info = await stat(full);
    if (info.isDirectory()) files.push(...(await walk(full)));
    else if (entry !== 'sw.js') files.push(path.relative(dist, full).split(path.sep).join('/'));
  }
  return files;
}

const files = await walk(dist);
if (!files.includes('index.html')) {
  console.error('dist/index.html is missing');
  process.exit(1);
}

const precache = files.map((file) => BASE + file);
const indexUrl = `${BASE}index.html`;
const rootUrl = BASE;
const cache = `piano-lab-${Date.now()}`;

const source = `/* Generated by scripts/emit-sw.mjs. Do not edit. */
const CACHE = ${JSON.stringify(cache)};
const PRECACHE = ${JSON.stringify(precache)};
const INDEX = ${JSON.stringify(indexUrl)};
const ROOT = ${JSON.stringify(rootUrl)};

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await cache.addAll(PRECACHE);
    const index = await cache.match(INDEX);
    if (index) await cache.put(ROOT, index.clone());
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    // Vite adds Vary: Origin. Ignore it so offline matches still hit.
    const match = (key) => cache.match(key, { ignoreVary: true });
    const path = url.pathname;
    const isNavigation = request.mode === 'navigate' || path === ROOT || path === '/piano-lab';
    if (isNavigation) {
      // Network first so a reload after deploy picks up the new script,
      // then fall back to the precache when the iPad is offline.
      try {
        const fresh = await fetch(request);
        if (fresh.ok && fresh.type === 'basic') {
          await cache.put(INDEX, fresh.clone());
          await cache.put(ROOT, fresh.clone());
          return fresh;
        }
      } catch {
        /* offline */
      }
      const cached = (await match(request)) || (await match(INDEX)) || (await match(ROOT));
      if (cached) return cached;
      return new Response('', { status: 503, statusText: 'offline' });
    }
    const cached = await match(request);
    if (cached) return cached;
    const response = await fetch(request);
    if (response.ok && response.type === 'basic') await cache.put(request, response.clone());
    return response;
  })());
});
`;

await writeFile(path.join(dist, 'sw.js'), source);
console.log(`service worker precaches ${precache.length} files`);
